// The words EngineBuddy's own UI uses, in each language it speaks. Model replies aren't translated:
// the model answers in the user's language by itself (the system prompt names the default).
//
// "system" follows Windows (main reads `app.getLocale()`); anything we don't have falls back to
// English. Main passes the resolved language to every renderer page as `?lang=`.

export const LANGUAGES = ['en', 'de', 'fr', 'es'] as const;
export type Lang = (typeof LANGUAGES)[number];
export const LANGUAGE_PREFS = ['system', ...LANGUAGES] as const;
export type LanguagePref = (typeof LANGUAGE_PREFS)[number];

/** Each language's name in itself, for the settings list and the system prompt. */
export const LANGUAGE_NAMES: Record<Lang, string> = {
  en: 'English',
  de: 'Deutsch',
  fr: 'Français',
  es: 'Español',
};

/** A locale like "de-DE" or "fr" → one of our languages, else English. */
export function langFromLocale(locale: string | undefined | null): Lang {
  const base = (locale ?? '').toLowerCase().split(/[-_]/)[0] ?? '';
  return (LANGUAGES as readonly string[]).includes(base) ? (base as Lang) : 'en';
}

export function resolveLang(pref: LanguagePref, systemLocale: string): Lang {
  return pref === 'system' ? langFromLocale(systemLocale) : pref;
}

